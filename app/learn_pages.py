def _t_rahu(cl: str, day: dt.date | None = None):
    n, ui = i18n.names(cl), UI[cl]
    head = [ui["th.weekday"], ui["th.part"]]
    live: dict[int, str] = {}
    if day is not None:
        head.append(ui["th.in_city"].format(city=_city_name(cl)))
        for off in range(7):
            d = day + dt.timedelta(days=off)
            q = _panchang(CITY.slug, d)
            live[q["vara"]["index"]] = (f"{_span(q['muhurta']['rahu_kaal'], d, cl)} "
                                        f"({i18n.format_date(d, cl, short=True)})")
    rows = []
    for v in range(7):
        row = [n.VARA.get(P.VARA_ENGLISH[v], P.VARA_ENGLISH[v]), str(P.RAHU_SEGMENT[v] + 1)]
        if day is not None:
            row.append(live[v])
        rows.append(row)
    return [("t.rahu.h", head, rows)]


def _t_choghadiya(cl: str, day: dt.date | None = None):
    n, ui = i18n.names(cl), UI[cl]

    def nm(x):
        return n.CHOGHADIYA.get(x, x)

    names = [[nm(k), n.GRAHA.get(v["ruler"], v["ruler"]),
              n.CHOGHADIYA_QUALITY.get(v["quality"], v["quality"])]
             for k, v in chog.CHOGHADIYA_INFO.items()]
    out = [("t.chog.names.h", [ui["th.name"], ui["th.ruler"], ui["th.class"]], names)]
    for key, table in (("t.chog.day.h", chog.DAY_SEQUENCE), ("t.chog.night.h", chog.NIGHT_SEQUENCE)):
        rows = [[n.VARA.get(P.VARA_ENGLISH[v], P.VARA_ENGLISH[v]), " → ".join(nm(x) for x in table[v])]
                for v in range(7)]
        out.append((key, [ui["th.weekday"], ui["th.seq"]], rows))
    if day is not None:
        p = _panchang(CITY.slug, day)
        slots, _ = _choghadiya_slots(p)
        rows = [[f"{_time(s['start'].isoformat(), day, cl)} – {_time(s['end'].isoformat(), day, cl)}",
                 nm(s["name"]), n.CHOGHADIYA_QUALITY.get(s["quality"], s["quality"])] for s in slots]
        out.append(("t.chog.today.h", [ui["th.when"], ui["th.name"], ui["th.class"]], rows))
    return out


