def _related(slug: str, cl: str) -> str:
    ui = UI[cl]
    keys, cta_tool = TOOLS[slug]
    items = [(_tool_href(k, cl), ui[_TOOL_UI[k]]) for k in keys]
    items.append((i18n.prefix(cl) + "/sitemap", ui["tool.sitemap"]))
    out = [f'<h2>{_e(ui["h.tool"])}</h2>',
           _cta(cta_tool, ui[_TOOL_UI[cta_tool]], cl),
           '<ul class="links">' + "".join(f"<li>{_link(h, t)}</li>" for h, t in items) + "</ul>"]
    for tool in ("panchang", *(k for k in keys if k in ("rahu-kaal", "choghadiya"))):
        cities = seo_cities.CITIES[:TOP_CITIES]
        out.append('<ul class="links">' + "".join(
            "<li>" + _link(_path(tool, c, cl), ui["tool.in_city"].format(
                tool=ui[_TOOL_UI[tool]], city=seo_cities.city_name(c, cl))) + "</li>"
            for c in cities) + "</ul>")
    out.append(f'<h2>{_e(ui["h.more"])}</h2><ul class="links">' + "".join(
        f"<li>{_link(page_path(s, cl), PAGES[s][cl]['label'])}</li>" for s in SLUGS if s != slug)
        + f"<li>{_link(page_path(None, cl), ui['learn'])}</li></ul>")
    return "\n".join(out)


def _faq(items) -> tuple[str, dict]:
    html_part = "".join(f"<h3>{_e(q)}</h3><p>{_e(a)}</p>" for q, a in items)
    ld = {"@type": FAQ_TYPE, "mainEntity": [
        {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}}
        for q, a in items]}
    return f'<div class="faq">{html_part}</div>', ld


def _tool_name_for_note(slug: str, cl: str) -> str:
    return UI[cl][_TOOL_UI[TOOLS[slug][0][0]]]


@functools.lru_cache(maxsize=64)
def _page_parts(slug: str, cl: str, day: dt.date) -> tuple[str, str, str, dict]:
    """(title, description, body, FAQPage JSON-LD) in content language `cl`."""
    t, ui = PAGES[slug][cl], UI[cl]
    key, values = live_values(slug, day, cl)
    live = _e(t[key].format(**values))
    if slug == "what-is-tithi":
        p = _panchang(CITY.slug, day)
        if len(p["tithi"]) > 1:
            n, nxt = i18n.names(cl), p["tithi"][1]
            live += _e(t["live2"].format(next=n.tithi_label(nxt["paksha"], nxt["name"]),
                                         next_end=_time(nxt["ends"], day, cl)))
    paragraphs = "".join(f"<p>{_e(x)}</p>" for x in t["method"])
    convention = (f'<p><strong>{_e(ui["conv"])}.</strong> {_e(t["convention"])}</p>'
                  if t.get("convention") else "")
    note = t.get("live_note", ui["live.note"]).format(tool=_tool_name_for_note(slug, cl))
    note_html = f"<p><small>{_e(note)}</small></p>" if note else ""
    tables = "".join(
        f'<h2>{_e(ui[hk].format(city=_city_name(cl)))}</h2>{_table(head, rows)}'
        for hk, head, rows in tables_for(slug, cl, day))
    examples = _mangal_examples(cl) if slug == "what-is-mangal-dosha" else ""
    faq_html, faq_ld = _faq(t["faq"])
    body = f"""
<h1>{_e(t["h1"])}</h1>
<div class="box"><p>{_e(t["answer"])}</p></div>
<h2>{_e(ui["h.method"])}</h2>
{paragraphs}
{convention}
<h2>{_e(t["live_h"] or ui["h.live"].format(city=_city_name(cl)))}</h2>
<div class="box"><p>{live}</p>{note_html}</div>
{examples}{tables}
<h2>{_e(ui["h.use"])}</h2>
{"".join(f"<p>{_e(x)}</p>" for x in t["use"])}
<h2>{_e(ui["h.faq"])}</h2>
{faq_html}
{_related(slug, cl)}
<p><small>{_e(ui["disclaimer"])}</small></p>"""
    return f"{t['title']} | {BRAND}", t["desc"], body, faq_ld


@functools.lru_cache(maxsize=8)
def _index_parts(cl: str) -> tuple[str, str, str]:
    ui = UI[cl]
    items = "".join(
        f'<h2>{_link(page_path(s, cl), PAGES[s][cl]["label"])}</h2><p>{_e(PAGES[s][cl]["blurb"])}</p>'
        for s in SLUGS)
    body = f'<h1>{_e(ui["index.h1"])}</h1>\n<p>{_e(ui["index.intro"])}</p>\n{items}\n<p><small>{_e(ui["disclaimer"])}</small></p>'
    return f"{ui['index.title']} | {BRAND}", ui["index.desc"], body


def _content_lang(lang: str) -> str:
    return lang if lang in TRANSLATED else "en"


def render_index(lang: str, status: int = 200) -> HTMLResponse:
    cl = _content_lang(lang)
    title, desc, body = _index_parts(cl)
    return _render(title=title, description=desc, path=page_path(None, lang),
                   crumbs=[(UI[cl]["learn"], page_path(None, lang))], body=body, lang=lang,
                   alt="twin" if status == 200 else None, status=status,
                   cache=status == 200, translated=TRANSLATED)


def render_page(slug: str, lang: str) -> HTMLResponse:
    cl = _content_lang(lang)
    title, desc, body, faq_ld = _page_parts(slug, cl, _today())
    return _render(title=title, description=desc, path=page_path(slug, lang),
                   crumbs=[(UI[cl]["learn"], page_path(None, lang)),
                           (PAGES[slug][cl]["label"], page_path(slug, lang))],
                   body=body, lang=lang, alt="twin", extra_ld=(faq_ld,), translated=TRANSLATED)


def _gate() -> None:
    if not enabled():
        raise HTTPException(status_code=404, detail="Not Found")


def _serve(slug: str | None, lang: str) -> HTMLResponse:
    _gate()
    if slug is None:
        return render_index(lang)
    if slug not in PAGES:
        return render_index(lang, status=404)    # a real 404 that still offers the pages
    return render_page(slug, lang)


