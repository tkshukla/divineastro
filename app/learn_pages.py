_PARKED = {"Sun": "Sagittarius", "Mercury": "Scorpio", "Saturn": "Aquarius"}
_CANCEL_KEYS = (("dignified", "cancel.dignified"), ("2nd house", "cancel.2"),
                ("4th house", "cancel.4"), ("7th house", "cancel.7"), ("8th house", "cancel.8"),
                ("12th house", "cancel.12"), ("Guru-Mangala", "cancel.jupiter"),
                ("Chandra-Mangala", "cancel.moon"))


class _Session:
    def __init__(self, bundle: dict):
        self.bundle = bundle


def mangal_session(chart: dict) -> _Session:
    """A minimal sidereal chart bundle for analyze_manglik: Lagna, seven grahas, whole-sign houses."""
    placed = {**_PARKED, **{k: v for k, v in chart.items() if k != "lagna"}}
    objects = {"ASC": {"sign": chart["lagna"], "longitude": SIGNS.index(chart["lagna"]) * 30 + 15.0}}
    for graha, sign in placed.items():
        objects[graha] = {"sign": sign, "longitude": SIGNS.index(sign) * 30 + 15.0,
                          "retrograde": False}
    first = SIGNS.index(chart["lagna"])
    return _Session({"meta": {"zodiac": "sidereal"}, "objects": objects,
                     "houses": {"signs": [SIGNS[(first + i) % 12] for i in range(12)]}})


@functools.lru_cache(maxsize=1)
def mangal_results() -> tuple[dict, ...]:
    return tuple(analyze_manglik(mangal_session(c)) for c in MANGAL_CHARTS)


def cancel_key(message: str) -> str | None:
    return next((key for needle, key in _CANCEL_KEYS if needle in message), None)


def _mangal_examples(cl: str) -> str:
    ui, n = UI[cl], i18n.names(cl)
    rows = []
    for k, (chart, res) in enumerate(zip(MANGAL_CHARTS, mangal_results()), 1):
        sg = lambda s: n.RASHI.get(s, s)   # noqa: E731
        setup = "; ".join(f"{ui['ex.' + g.lower()]}: {sg(chart[g] if g != 'Lagna' else chart['lagna'])}"
                          for g in ("Lagna", "Mars", "Moon", "Venus", "Jupiter"))
        h = res["houses"]
        lines = [_e(ui["ex.houses"].format(lagna=h["from_lagna"], moon=h["from_moon"],
                                           venus=h["from_venus"]))]
        if res["is_manglik"]:
            lines.append(_e(ui["ex.manglik"].format(score=f"{res['score']:.1f}")))
        elif res["is_cancelled"]:
            lines.append(_e(ui["ex.cancelled"]))
            lines.append("<ul>" + "".join(
                f"<li>{_e(ui[cancel_key(c)] if cancel_key(c) else c)}</li>"
                for c in res["cancellations"]) + "</ul>")
        else:
            lines.append(_e(ui["ex.clear"]))
        rows.append(f"<tr><td><strong>{_e(ui['ex.label'].format(k=k))}</strong><br>{_e(setup)}</td>"
                    f"<td>{'<br>'.join(lines)}</td></tr>")
    head = f'<tr><th scope="col">{_e(ui["th.chart"])}</th><th scope="col">{_e(ui["th.result"])}</th></tr>'
    return f'<h2>{_e(ui["t.mangal.example.h"])}</h2><div class="scroll"><table>{head}{"".join(rows)}</table></div>'


