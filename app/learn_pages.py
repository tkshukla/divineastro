def _ui(cl: str, key: str, **values) -> str:
    text = UI[cl][key]
    return text.format(**values) if values else text


def _min(minutes: float) -> str:
    return f"{minutes:.0f}"


def _tithi_label(index: int) -> tuple[str, str, int]:
    """0-based tithi index -> (name, paksha, number in the paksha); panchang._tithi_label's rule."""
    within = index % 15
    paksha = "Shukla" if index < 15 else "Krishna"
    name = P.TITHI_NAMES[within]
    if within == 14:
        name = "Purnima" if paksha == "Shukla" else "Amavasya"
    return name, paksha, within + 1


def _clock_span(a: dt.datetime, b: dt.datetime, day: dt.date, cl: str) -> str:
    return f"{_time(a.isoformat(), day, cl)} – {_time(b.isoformat(), day, cl)}"


def _sunrise_sunset(day: dt.date, offset: int = 0):
    return P.sun_times(day + dt.timedelta(days=offset), CITY.latitude, CITY.longitude, CITY.timezone)


def _link(href: str, text: str) -> str:
    return f'<a href="{_e(href)}">{_e(text)}</a>'


def _cell(c) -> str:
    """A table cell: plain text (escaped), or (text, href) for a link."""
    if isinstance(c, tuple):
        return _link(c[1], c[0])
    return _e(c)


def _table(head: list[str], rows: list[list]) -> str:
    th = "".join(f'<th scope="col">{_e(h)}</th>' for h in head)
    body = "".join("<tr>" + "".join(f"<td>{_cell(c)}</td>" for c in r) + "</tr>" for r in rows)
    return f'<div class="scroll"><table><tr>{th}</tr>{body}</table></div>'


def _text(c) -> str:
    return c[0] if isinstance(c, tuple) else c


