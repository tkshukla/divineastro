def _md_table(head: list[str], rows: list[list]) -> str:
    esc = lambda c: str(_text(c)).replace("|", "\\|")   # noqa: E731
    return "\n".join(["| " + " | ".join(esc(h) for h in head) + " |",
                      "|" + "|".join("---" for _ in head) + "|",
                      *("| " + " | ".join(esc(c) for c in r) + " |" for r in rows)])


