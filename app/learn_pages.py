def live_values(slug: str, day: dt.date, cl: str) -> tuple[str, dict]:
    """(template key, values) of the worked example for `slug` on `day`."""
    n = i18n.names(cl)
    p = _panchang(CITY.slug, day)
    v = _common(day, cl)
    m = p["muhurta"]

    if slug == "what-is-panchang":
        t, k, y, ka = p["tithi"][0], p["nakshatra"][0], p["yoga"][0], p["karana"][0]
        v.update(tithi=n.tithi_label(t["paksha"], t["name"]), tithi_end=_time(t["ends"], day, cl))
        v["nakshatra"], v["nak_end"] = _limb(k, day, cl, n.NAKSHATRAS)
        v["yoga"], v["yoga_end"] = _limb(y, day, cl, n.YOGA)
        v["karana"], v["karana_end"] = _limb(ka, day, cl, n.KARANA)
        v["sunrise"], v["sunset"] = _time(p["sun"]["rise"], day, cl), _time(p["sun"]["set"], day, cl)
        return "live", v
    if slug == "what-is-tithi":
        t = p["tithi"][0]
        v.update(tithi=n.tithi_label(t["paksha"], t["name"]), start=_time(t["starts"], day, cl),
                 end=_time(t["ends"], day, cl))
        return "live", v
    if slug == "what-is-nakshatra":
        k = p["nakshatra"][0]
        v.update(nakshatra=n.NAKSHATRAS.get(k["name"], k["name"]), pada=str(k["pada"]),
                 end=_time(k["ends"], day, cl))
        return "live", v
    if slug == "what-is-yoga-and-karana":
        v["yoga"], v["yoga_end"] = _limb(p["yoga"][0], day, cl, n.YOGA)
        v["karana"], v["karana_end"] = _limb(p["karana"][0], day, cl, n.KARANA)
        return "live", v
    if slug == "what-is-rahu-kaal":
        r = m["rahu_kaal"]
        v.update(rahu=_span(r, day, cl), part=str(r["segment"]), minutes=_min(r["duration_minutes"]),
                 sunrise=_time(p["sun"]["rise"], day, cl), sunset=_time(p["sun"]["set"], day, cl))
        return "live", v
    if slug == "what-is-choghadiya":
        day_slots, _ = _choghadiya_slots(p)
        first = day_slots[0]
        v.update(first=n.CHOGHADIYA.get(first["name"], first["name"]),
                 first_when=_clock_span(first["start"], first["end"], day, cl),
                 sunrise=_time(p["sun"]["rise"], day, cl), sunset=_time(p["sun"]["set"], day, cl),
                 minutes=_min((first["end"] - first["start"]).total_seconds() / 60))
        return "live", v
    if slug == "what-is-abhijit-muhurat":
        a = m["abhijit"]
        if a:
            v.update(abhijit=_span(a, day, cl), minutes=_min(a["duration_minutes"]),
                     sunrise=_time(p["sun"]["rise"], day, cl), sunset=_time(p["sun"]["set"], day, cl))
            return "live", v
        d2 = day + dt.timedelta(days=1)
        a2 = _panchang(CITY.slug, d2)["muhurta"]["abhijit"]
        v.update(date2=_long_date(d2, cl), abhijit2=_span(a2, d2, cl),
                 minutes2=_min(a2["duration_minutes"]))
        return "live_none", v
    if slug == "what-is-brahma-muhurta":
        ss, start, end, sr = _brahma(day)
        v.update(sunset_prev=_time(ss.isoformat(), day, cl), sunrise=_time(sr.isoformat(), day, cl),
                 brahma=_clock_span(start, end, day, cl), minutes=_min((end - start).total_seconds() / 60))
        return "live", v
    if slug == "what-is-pradosh-kaal":
        _, sunset, next_sunrise = _sunrise_sunset(day)
        night = next_sunrise - sunset
        end = sunset + night * 3 / 15
        v.update(sunset=_time(sunset.isoformat(), day, cl), pradosh=_clock_span(sunset, end, day, cl),
                 minutes=_min((end - sunset).total_seconds() / 60),
                 dating=_clock_span(sunset, sunset + dt.timedelta(minutes=96), day, cl))
        return "live", v
    if slug == "what-is-sade-sati":
        saturn_idx, retro = saturn_now(day)
        signs = [nakshatra_pages._sign_name((saturn_idx + d) % 12, cl) for d in (-1, 0, 1)]
        v.update(saturn=nakshatra_pages._sign_name(saturn_idx, cl),
                 motion=UI[cl]["motion.retro" if retro else "motion.direct"],
                 signs=f"{signs[0]}, {signs[1]} {UI[cl]['and']} {signs[2]}")
        return "live", v
    if slug == "what-is-mangal-dosha":
        return "live", v
    raise KeyError(slug)


@functools.lru_cache(maxsize=8)
def saturn_now(day: dt.date) -> tuple[int, bool]:
    """(Saturn's sidereal sign index, retrograde?) at midnight IST on `day`, from the same
    function the Kundali's Sade Sati panel uses (one year's window keeps it cheap)."""
    r = P.sade_sati_for_moon_sign(0, dt.datetime(day.year, day.month, day.day, tzinfo=IST),
                                  timezone=CITY.timezone, window_years=1.0)
    return SIGNS.index(r["saturn"]["sign"]), bool(r["saturn"]["retrograde"])


